"""The evaluation set and the runs over it, as files in the repository.

The local database and the PDFs are not versioned, so the notices of the evaluation set
(API metadata, items and page text) and every published run's answers are written here.
`radar report` scores those files without a database or an API key, which is how CI
checks on every push that the published numbers still follow from the code.
"""

from __future__ import annotations

import gzip
import json
import sqlite3
from dataclasses import asdict
from pathlib import Path
from typing import Any

from radar import retrieve
from radar.evaluate import (
    Notice,
    Prediction,
    Report,
    load_notices,
    load_run,
    score,
    to_markdown,
)
from radar.labels import ANNOTATIONS, GOLD_FIELDS
from radar.schema import FIELDS

EVALS = Path("evals")
DATASET = EVALS / "dataset.jsonl.gz"
RUNS = EVALS / "runs"
REPORT = EVALS / "REPORT.md"


def export_dataset(conn: sqlite3.Connection, numbers: list[str], path: Path = DATASET) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    notices = load_notices(conn, numbers)
    # mtime=0 keeps the file byte-identical when nothing changed, so git sees no diff.
    with (
        open(path, "wb") as raw,
        gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as packed,
    ):
        for number in numbers:
            line = json.dumps(asdict(notices[number]), ensure_ascii=False) + "\n"
            packed.write(line.encode("utf-8"))
    return len(numbers)


def load_dataset(path: Path = DATASET) -> dict[str, Notice]:
    with gzip.open(path, "rt", encoding="utf-8") as lines:
        return {n["control_number"]: Notice(**n) for n in map(json.loads, lines)}


def export_run(conn: sqlite3.Connection, run_id: int, name: str, runs: Path = RUNS) -> Path:
    run, predictions = load_run(conn, run_id)
    runs.mkdir(parents=True, exist_ok=True)
    path = runs / f"{name}.json"
    document = {
        "model": run["model"],
        "strategy": run["strategy"],
        "prompt_version": run["prompt_version"],
        "predictions": [asdict(p) for p in predictions],
    }
    path.write_text(json.dumps(document, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return path


def load_runs(runs: Path = RUNS) -> list[tuple[str, dict[str, Any], list[Prediction]]]:
    loaded = []
    for path in sorted(runs.glob("*.json")):
        document = json.loads(path.read_text(encoding="utf-8"))
        predictions = [Prediction(**p) for p in document.pop("predictions")]
        loaded.append((path.stem, document, predictions))
    return loaded


def _accuracy(report: Report, fields: list[str]) -> str:
    correct = sum(report.fields[f].outcomes["correct"] for f in fields)
    labelled = sum(report.fields[f].labelled for f in fields)
    return f"{correct / labelled:.0%}" if labelled else "-"


def _p(values: list[int], q: float) -> int:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(q * len(ordered)))] if ordered else 0


def retrieval_recall(
    notices: dict[str, Notice], annotations: Path = ANNOTATIONS
) -> dict[str, tuple[int, int]]:
    """Per gold field, in how many notices the page that settles the answer is among the
    excerpts the retrieve strategy sends: (sent, notices with a settling page)."""
    gold_pages = _gold_pages(annotations)
    recall = {}
    for field in GOLD_FIELDS:
        sent = total = 0
        for number, notice in notices.items():
            page = gold_pages.get(number, {}).get(field, {}).get("page")
            if page is None:
                continue
            total += 1
            sent += any(s.page == page for s in retrieve.select(notice.pages))
        recall[field] = (sent, total)
    return recall


def _gold_pages(annotations: Path) -> dict[str, dict[str, dict[str, Any]]]:
    path = annotations / "gold.jsonl"
    if not path.exists():
        return {}
    lines = path.read_text(encoding="utf-8").splitlines()
    return {e["control_number"]: e["fields"] for e in map(json.loads, filter(None, lines))}


def build_report(
    dataset: Path = DATASET, runs: Path = RUNS, annotations: Path = ANNOTATIONS
) -> str:
    notices = load_dataset(dataset)
    silver_fields = [f for f in FIELDS if f not in GOLD_FIELDS]
    scored = [
        (name, meta, score(name, meta["model"], notices, predictions, annotations))
        for name, meta, predictions in load_runs(runs)
    ]
    lines = [
        "# Evaluation report",
        "",
        "Generated by `radar report` from `evals/`; CI fails if this file is out of date.",
        f"{len(notices)} notices from Rio de Janeiro, October 2026. Silver labels come from",
        "the PNCP API (only where the edital states them, corrected by hand where they",
        "disagree); gold labels are annotated, see `docs/annotation.md`.",
        "",
        "| Run | Model | Strategy | Valid | Silver fields | Gold fields | Quotes on page "
        "| Tokens in (p50) | Latency p50 / p95 |",
        "| --- | --- | --- | --: | --: | --: | --: | --: | --: |",
    ]
    for name, meta, report in scored:
        quotes = sum(report.grounding.values())
        on_page = f"{report.grounding['on_page'] / quotes:.0%}" if quotes else "-"
        lines.append(
            f"| {name} | `{meta['model']}` | {meta['strategy']} "
            f"| {report.notices - report.failures}/{report.notices} "
            f"| {_accuracy(report, silver_fields)} | {_accuracy(report, GOLD_FIELDS)} "
            f"| {on_page} | {_p(report.tokens_in, 0.5):,} "
            f"| {_p(report.latency_ms, 0.5) / 1000:.1f}s "
            f"/ {_p(report.latency_ms, 0.95) / 1000:.1f}s |"
        )
    recall = retrieval_recall(notices, annotations)
    lines += [
        "",
        f"## Retrieval (version {retrieve.VERSION})",
        "",
        "How often the page that settles a gold label is among the excerpts the retrieve",
        "strategy sends. The patterns were tuned on these same notices, so this is an",
        "optimistic estimate of how retrieval does on unseen editais.",
        "",
        "| Field | Settling page sent |",
        "| --- | --: |",
    ]
    for field, (sent, total) in recall.items():
        lines.append(f"| `{field}` | {sent}/{total} |")
    for _, meta, report in scored:
        lines += ["", to_markdown(report), "", f"Prompt version {meta['prompt_version']}."]
    return "\n".join(lines) + "\n"


def import_dataset(conn: sqlite3.Connection, path: Path = DATASET) -> int:
    """Load the evaluation set into an empty database, for CI, where there are no PDFs."""
    notices = load_dataset(path)
    with conn:
        for notice in notices.values():
            meta = notice.metadata
            conn.execute(
                """
                INSERT OR IGNORE INTO notices (control_number, cnpj, year, sequence,
                    published_at, metadata, items, pdf_sha256, pdf_title)
                VALUES (?, ?, ?, ?, ?, ?, ?, 'from-dataset', 'from-dataset')
                """,
                (
                    notice.control_number,
                    meta["orgaoEntidade"]["cnpj"],
                    meta["anoCompra"],
                    meta["sequencialCompra"],
                    meta["dataPublicacaoPncp"],
                    json.dumps(meta, ensure_ascii=False),
                    json.dumps(notice.items, ensure_ascii=False),
                ),
            )
            conn.executemany(
                "INSERT OR IGNORE INTO pages (control_number, page, text) VALUES (?, ?, ?)",
                [(notice.control_number, n, text) for n, text in enumerate(notice.pages, 1)],
            )
    return len(notices)
